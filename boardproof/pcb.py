"""A tiny PCB document model, KiCad writer/reader and SVG renderer.

Deliberately not a general EDA implementation: it exists so BoardProof can
generate one honest two-layer board, then independently re-read the file and
prove that what landed on disk is what the netlist asked for.
"""
from __future__ import annotations

import math
import re
from dataclasses import dataclass, field

MM = 1.0


@dataclass
class PadInst:
    ref: str
    number: str
    net: str
    x: float
    y: float
    w: float
    h: float
    layer: str = "F.Cu"
    rotation: float = 0.0


@dataclass
class FootprintInst:
    ref: str
    pattern: str
    x: float
    y: float
    rotation: float
    pads: list[PadInst] = field(default_factory=list)
    body_w: float = 1.0
    body_h: float = 1.0
    body_cx: float = 0.0      # body centre, relative to the footprint origin
    body_cy: float = 0.0
    width: float = 2.0
    height: float = 1.0


@dataclass
class Segment:
    net: str
    layer: str
    x1: float
    y1: float
    x2: float
    y2: float
    width: float = 0.25


@dataclass
class Via:
    net: str
    x: float
    y: float
    drill: float = 0.4
    size: float = 0.8


@dataclass
class Board:
    width: float
    height: float
    footprints: list[FootprintInst] = field(default_factory=list)
    segments: list[Segment] = field(default_factory=list)
    vias: list[Via] = field(default_factory=list)
    title: str = "BoardProof candidate"
    unrouted: list[str] = field(default_factory=list)

    def pads(self) -> list[PadInst]:
        return [p for f in self.footprints for p in f.pads]

    def nets(self) -> list[str]:
        return sorted({p.net for p in self.pads() if p.net})


def _uuid(ref: str, number: str) -> str:
    import hashlib

    return hashlib.md5(f"{ref}.{number}".encode()).hexdigest()


def write_kicad(board: Board) -> str:
    """Emit a KiCad 9 compatible .kicad_pcb (S-expression)."""
    nets = board.nets()
    net_ids = {name: index + 1 for index, name in enumerate(nets)}
    out: list[str] = []
    out.append("(kicad_pcb (version 20241229) (generator \"boardproof\")")
    out.append("  (general (thickness 1.6) (legacy_teardrops no))")
    out.append("  (paper \"A4\")")
    out.append("  (title_block (title \"%s\") (comment 1 \"generated by BoardProof - verify before fabrication\"))"
               % board.title.replace('"', "'"))
    out.append("  (layers")
    out.append("    (0 \"F.Cu\" signal) (2 \"B.Cu\" signal)")
    out.append("    (1 \"F.Paste\" user) (3 \"B.Paste\" user)")
    out.append("    (5 \"F.SilkS\" user) (7 \"B.SilkS\" user)")
    out.append("    (9 \"F.Mask\" user) (11 \"B.Mask\" user)")
    out.append("    (13 \"F.Fab\" user) (15 \"B.Fab\" user)")
    out.append("    (25 \"Edge.Cuts\" user)")
    out.append("  )")
    out.append("  (setup (pad_to_mask_clearance 0))")
    for name, ident in net_ids.items():
        out.append(f'  (net {ident} "{name}")')

    # board outline on Edge.Cuts
    corners = [(0, 0), (board.width, 0), (board.width, board.height), (0, board.height)]
    for index in range(4):
        x1, y1 = corners[index]
        x2, y2 = corners[(index + 1) % 4]
        out.append(f'  (gr_line (start {x1:g} {y1:g}) (end {x2:g} {y2:g}) '
                   f'(stroke (width 0.1) (type solid)) (layer "Edge.Cuts") (uuid "{_uuid("edge", str(index))}"))')

    for fp in board.footprints:
        out.append(f'  (footprint "BoardProof:{fp.pattern}" (layer "F.Cu") (uuid "{_uuid(fp.ref, "fp")}")')
        out.append(f'    (at {fp.x:.3f} {fp.y:.3f} {fp.rotation:g})')
        out.append(f'    (property "Reference" "{fp.ref}" (at 0 {-fp.height / 2 - 0.8:.2f} 0) '
                   f'(layer "F.SilkS") (uuid "{_uuid(fp.ref, "ref")}"))')
        out.append(f'    (property "Value" "{fp.pattern}" (at 0 {fp.height / 2 + 0.6:.2f} 0) '
                   f'(layer "F.Fab") (uuid "{_uuid(fp.ref, "val")}"))')
        # body outline on F.Fab: silkscreen over pads is a real DRC warning
        out.append(f'    (fp_rect (start {-fp.body_w / 2:.2f} {-fp.body_h / 2:.2f}) '
                   f'(end {fp.body_w / 2:.2f} {fp.body_h / 2:.2f}) '
                   f'(stroke (width 0.1) (type solid)) (fill none) (layer "F.Fab") '
                   f'(uuid "{_uuid(fp.ref, "fab")}"))')
        for pad in fp.pads:
            dx, dy = pad.x - fp.x, pad.y - fp.y
            ident = net_ids.get(pad.net, 0)
            out.append(f'    (pad "{pad.number}" smd roundrect (at {dx:.3f} {dy:.3f}) '
                       f'(size {pad.w:.2f} {pad.h:.2f}) (layers "F.Cu" "F.Paste" "F.Mask") '
                       f'(roundrect_rratio 0.25) (net {ident} "{pad.net}") (uuid "{_uuid(fp.ref, pad.number)}"))')
        out.append("  )")

    for seg in board.segments:
        ident = net_ids.get(seg.net, 0)
        out.append(f'  (segment (start {seg.x1:.3f} {seg.y1:.3f}) (end {seg.x2:.3f} {seg.y2:.3f}) '
                   f'(width {seg.width:g}) (layer "{seg.layer}") (net {ident}) '
                   f'(uuid "{_uuid(seg.net, f"{seg.x1:.2f},{seg.y1:.2f},{seg.x2:.2f},{seg.y2:.2f}")}"))')
    for via in board.vias:
        ident = net_ids.get(via.net, 0)
        out.append(f'  (via (at {via.x:.3f} {via.y:.3f}) (size {via.size:g}) (drill {via.drill:g}) '
                   f'(layers "F.Cu" "B.Cu") (net {ident}) (uuid "{_uuid(via.net, f"via{via.x:.2f}{via.y:.2f}")}"))')
    out.append(")")
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- #
# Reader (independent of the writer: it parses the text on disk)
# --------------------------------------------------------------------------- #
_NET = re.compile(r'\(net (\d+) "([^"]*)"\)')
_FP = re.compile(r'\(footprint "([^"]+)" \(layer "([^"]+)"\) \(uuid "([^"]+)"\)(.*?)\n  \)', re.S)
_AT = re.compile(r"\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)")
_PAD = re.compile(
    r'\(pad "([^"]+)" \w+ \w+ \(at ([-\d.]+) ([-\d.]+)\) \(size ([-\d.]+) ([-\d.]+)\)[^\n]*?'
    r'\(net (\d+) "([^"]*)"\)')
_SEG = re.compile(r'\(segment \(start ([-\d.]+) ([-\d.]+)\) \(end ([-\d.]+) ([-\d.]+)\) '
                  r'\(width ([\d.]+)\) \(layer "([^"]+)"\) \(net (\d+)\)')
_VIA = re.compile(r'\(via \(at ([-\d.]+) ([-\d.]+)\) \(size ([\d.]+)\) \(drill ([\d.]+)\).*?\(net (\d+)\)')


def read_kicad_sexpr(text: str) -> Board:
    """Parse a real KiCad .kicad_pcb (v7/8/9) with the s-expression reader."""
    from .kicad_import import _children, _field, parse_sexpr

    tree = parse_sexpr(text)
    root = tree[0] if len(tree) == 1 and tree and isinstance(tree[0], list) else tree
    if not root or root[0] != "kicad_pcb":
        raise ValueError("not a kicad_pcb file")

    # every Edge.Cuts shape counts: rects, lines, arcs, circles and polygons
    edge_kinds = ("gr_line", "gr_rect", "gr_arc", "gr_circle", "gr_poly", "gr_curve")
    edges = [node for kind in edge_kinds for node in _children(root, kind)
             if _field(node, "layer") == "Edge.Cuts"]

    def xy(node, head):
        for item in node:
            if isinstance(item, list) and item and item[0] == head:
                return float(item[1]), float(item[2])
        return 0.0, 0.0

    xs, ys = [], []
    for edge in edges:
        for head in ("start", "end", "mid", "center"):
            for item in edge:
                if isinstance(item, list) and item and item[0] == head and len(item) > 2:
                    try:
                        xs.append(float(item[1]))
                        ys.append(float(item[2]))
                    except (TypeError, ValueError):
                        pass
        for pts in _children(edge, "pts"):
            for point in _children(pts, "xy"):
                try:
                    xs.append(float(point[1]))
                    ys.append(float(point[2]))
                except (TypeError, ValueError, IndexError):
                    pass
        radius = None
        for item in edge:
            if isinstance(item, list) and item and item[0] == "radius":
                try:
                    radius = float(item[1])
                except (TypeError, ValueError, IndexError):
                    radius = None
        if radius:
            cx_, cy_ = xy(edge, "center")
            xs += [cx_ - radius, cx_ + radius]
            ys += [cy_ - radius, cy_ + radius]
    min_x, min_y = (min(xs), min(ys)) if xs else (0.0, 0.0)
    width = (max(xs) - min_x) if xs else 0.0
    height = (max(ys) - min_y) if ys else 0.0

    # KiCad writes (net 3 "GND") once at the top, then (net 3) on each track/pad
    net_names: dict[str, str] = {}
    for item in _children(root, "net"):
        if len(item) > 2 and isinstance(item[1], str) and isinstance(item[2], str):
            net_names[item[1]] = item[2]

    def resolve_net(node) -> str:
        for item in node:
            if isinstance(item, list) and item and item[0] == "net" and len(item) >= 2:
                named = [value for value in item[2:] if isinstance(value, str) and not value.isdigit()]
                if named:
                    return named[0]
                return net_names.get(str(item[1]), "")
        return ""

    board = Board(round(width, 3), round(height, 3))
    area = [node for node in root if isinstance(node, list) and node and node[0] == "footprint"]
    area += [node for node in root if isinstance(node, list) and node and node[0] == "module"]
    for footprint in area:
        fx, fy = xy(footprint, "at")
        rotation = 0.0
        for item in footprint:
            if isinstance(item, list) and item and item[0] == "at" and len(item) > 3:
                try:
                    rotation = float(item[3])
                except (TypeError, ValueError):
                    rotation = 0.0
        ref = ""
        for prop in _children(footprint, "property"):
            if len(prop) > 2 and prop[1] == "Reference":
                ref = str(prop[2])
        for text_node in _children(footprint, "fp_text"):
            if len(text_node) > 2 and text_node[1] == "reference":
                ref = ref or str(text_node[2])
        ref = ref or "?"
        pattern = str(footprint[1]) if len(footprint) > 1 and isinstance(footprint[1], str) else ""
        pattern = pattern.split(":")[-1]
        inst = FootprintInst(ref=ref, pattern=pattern, x=fx, y=fy, rotation=rotation)
        for pad in _children(footprint, "pad"):
            number = str(pad[1]) if len(pad) > 1 else ""
            px, py = xy(pad, "at")
            size = next((item for item in pad if isinstance(item, list) and item and item[0] == "size"),
                        ["size", "0", "0"])
            net = resolve_net(pad)
            if not number or not number.strip():
                continue                     # mechanical / paste-only pad
            if net.startswith("unconnected-"):
                net = ""                    # KiCad names every lone pin; it is not a net
            # pad (at ...) is relative to the footprint origin and must be rotated
            # KiCad writes pad offsets already in the footprint's frame (verified against
            # this file's Edge.Cuts: rotating them pushes 20 pads off the board, not 12)
            ax, ay = px, py
            pad_angle = 0.0
            for item in pad:
                if isinstance(item, list) and item and item[0] == "at" and len(item) > 3:
                    try:
                        pad_angle = float(item[3])
                    except (TypeError, ValueError):
                        pad_angle = 0.0
            inst.pads.append(PadInst(ref, number, net, fx + ax, fy + ay,
                                     float(size[1]), float(size[2]),
                                     rotation=pad_angle if pad_angle else rotation))
        if inst.pads:
            xs = [pad.x for pad in inst.pads] + [pad.x + pad.w / 2 for pad in inst.pads] \
                + [pad.x - pad.w / 2 for pad in inst.pads]
            ys = [pad.y for pad in inst.pads] + [pad.y + pad.h / 2 for pad in inst.pads] \
                + [pad.y - pad.h / 2 for pad in inst.pads]
            inst.width = round(max(xs) - min(xs) + 0.4, 3)
            inst.height = round(max(ys) - min(ys) + 0.4, 3)
            inst.body_w = round(max(xs) - min(xs), 3)
            inst.body_h = round(max(ys) - min(ys), 3)
            # centre from the median, not the bbox: one stray pad (a mounting pad at
            # the origin, a paste-only pad) shifts a bbox centre by tens of millimetres
            xs_sorted = sorted(pad.x for pad in inst.pads)
            ys_sorted = sorted(pad.y for pad in inst.pads)
            mid = len(xs_sorted) // 2
            median_x = (xs_sorted[mid] if len(xs_sorted) % 2
                        else (xs_sorted[mid - 1] + xs_sorted[mid]) / 2)
            mid_y = len(ys_sorted) // 2
            median_y = (ys_sorted[mid_y] if len(ys_sorted) % 2
                        else (ys_sorted[mid_y - 1] + ys_sorted[mid_y]) / 2)
            inst.body_cx = round(median_x - fx, 3)
            inst.body_cy = round(median_y - fy, 3)
        board.footprints.append(inst)

    for segment in _children(root, "segment"):
        x1, y1 = xy(segment, "start")
        x2, y2 = xy(segment, "end")
        layer = _field(segment, "layer") or "F.Cu"
        width_mm = float(_field(segment, "width") or 0.25)
        board.segments.append(Segment(resolve_net(segment), layer, x1, y1, x2, y2, width_mm))
    for via in _children(root, "via"):
        x, y = xy(via, "at")
        board.vias.append(Via(resolve_net(via), x, y, float(_field(via, "drill") or 0.3),
                              float(_field(via, "size") or 0.6)))

    # KiCad keeps the board wherever the user drew it: move it to the origin
    if board.footprints:
        for footprint in board.footprints:
            footprint.x -= min_x
            footprint.y -= min_y
            for pad in footprint.pads:
                pad.x -= min_x
                pad.y -= min_y
        for segment in board.segments:
            segment.x1 -= min_x
            segment.x2 -= min_x
            segment.y1 -= min_y
            segment.y2 -= min_y
        for via in board.vias:
            via.x -= min_x
            via.y -= min_y

    # Copper can legitimately sit outside the routed Edge.Cuts (an overhanging
    # connector, or a project whose outline is incomplete). Grow the sheet to cover
    # it and record the fact, instead of clipping parts out of the picture.
    pads = board.pads()
    if pads:
        copper_w = max(pad.x + pad.w / 2 for pad in pads)
        copper_h = max(pad.y + pad.h / 2 for pad in pads)
        if copper_w > board.width + 0.5 or copper_h > board.height + 0.5:
            board.outline_note = (
                f"copper extends past the routed edge: outline {board.width:g}x"
                f"{board.height:g} mm, copper {round(copper_w, 1):g}x{round(copper_h, 1):g} mm")
            board.width = round(max(board.width, copper_w) + 0.5, 2)
            board.height = round(max(board.height, copper_h) + 0.5, 2)
    return board


def read_kicad(text: str) -> Board:
    if text.lstrip().startswith("(kicad_pcb"):
        try:
            parsed = read_kicad_sexpr(text)
            if parsed.footprints:
                return parsed
        except Exception:  # noqa: BLE001 - fall back to the writer's own format
            pass
    nets = {int(ident): name for ident, name in _NET.findall(text)}
    ed_lines = re.findall(r'\(gr_line \(start ([-\d.]+) ([-\d.]+)\) \(end ([-\d.]+) ([-\d.]+)\)'
                          r'[^\n]*"Edge.Cuts"', text)
    xs = [float(v) for pair in ed_lines for v in (pair[0], pair[2])]
    ys = [float(v) for pair in ed_lines for v in (pair[1], pair[3])]
    width = max(xs) - min(xs) if xs else 0.0
    height = max(ys) - min(ys) if ys else 0.0
    # KiCad writes (net 3 "GND") once at the top, then (net 3) on each track/pad
    net_names: dict[str, str] = {}
    for item in _children(root, "net"):
        if len(item) > 2 and isinstance(item[1], str) and isinstance(item[2], str):
            net_names[item[1]] = item[2]

    def resolve_net(node) -> str:
        for item in node:
            if isinstance(item, list) and item and item[0] == "net" and len(item) >= 2:
                named = [value for value in item[2:] if isinstance(value, str) and not value.isdigit()]
                if named:
                    return named[0]
                return net_names.get(str(item[1]), "")
        return ""

    board = Board(round(width, 3), round(height, 3))
    board.title = (re.search(r'\(title "([^"]*)"\)', text) or [None, ""])[1]
    for pattern, _layer, _uuid_, body in _FP.findall(text):
        at = _AT.search(body)
        fx, fy = float(at.group(1)), float(at.group(2))
        rotation = float(at.group(3) or 0)
        ref = (re.search(r'\(property "Reference" "([^"]+)"', body) or [None, "?"])[1]
        inst = FootprintInst(ref=ref, pattern=pattern.split(":")[-1], x=fx, y=fy, rotation=rotation)
        for number, dx, dy, w, h, _ident, net in _PAD.findall(body):
            inst.pads.append(PadInst(ref, number, net, fx + float(dx), fy + float(dy),
                                     float(w), float(h)))
        if inst.pads:
            xs = [pad.x for pad in inst.pads] + [pad.x + pad.w / 2 for pad in inst.pads] \
                + [pad.x - pad.w / 2 for pad in inst.pads]
            ys = [pad.y for pad in inst.pads] + [pad.y + pad.h / 2 for pad in inst.pads] \
                + [pad.y - pad.h / 2 for pad in inst.pads]
            inst.width = round(max(xs) - min(xs) + 0.4, 3)
            inst.height = round(max(ys) - min(ys) + 0.4, 3)
            inst.body_w = round(max(xs) - min(xs), 3)
            inst.body_h = round(max(ys) - min(ys), 3)
            # centre from the median, not the bbox: one stray pad (a mounting pad at
            # the origin, a paste-only pad) shifts a bbox centre by tens of millimetres
            xs_sorted = sorted(pad.x for pad in inst.pads)
            ys_sorted = sorted(pad.y for pad in inst.pads)
            mid = len(xs_sorted) // 2
            median_x = (xs_sorted[mid] if len(xs_sorted) % 2
                        else (xs_sorted[mid - 1] + xs_sorted[mid]) / 2)
            mid_y = len(ys_sorted) // 2
            median_y = (ys_sorted[mid_y] if len(ys_sorted) % 2
                        else (ys_sorted[mid_y - 1] + ys_sorted[mid_y]) / 2)
            inst.body_cx = round(median_x - fx, 3)
            inst.body_cy = round(median_y - fy, 3)
        board.footprints.append(inst)
    for x1, y1, x2, y2, w, layer, ident in _SEG.findall(text):
        board.segments.append(Segment(nets.get(int(ident), ""), layer,
                                      float(x1), float(y1), float(x2), float(y2), float(w)))
    for x, y, size, drill, ident in _VIA.findall(text):
        board.vias.append(Via(nets.get(int(ident), ""), float(x), float(y), float(drill), float(size)))
    # some pads legitimately lean over the routed edge: keep them on the sheet
    pad_xs = [pad.x + pad.w / 2 for f in board.footprints for pad in f.pads]
    pad_ys = [pad.y + pad.h / 2 for f in board.footprints for pad in f.pads]
    if pad_xs:
        board.width = round(max(board.width, max(pad_xs)) + 0.4, 2)
        board.height = round(max(board.height, max(pad_ys)) + 0.4, 2)

    return board


