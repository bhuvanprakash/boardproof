def render_svg(board: Board, scale: float = 17.0) -> str:
    """Draw the board as a dimensioned figure, not a thumbnail.

    Dimension callouts above and to the left make the render read as a drawing:
    the reader can judge scale without a legend.
    """
    top, left, right, bottom = 20.0, 34.0, 6.0, 6.0
    w = board.width * scale + left + right
    h = board.height * scale + top + bottom

    def px(x: float) -> float:
        return left + x * scale

    def py(y: float) -> float:
        return top + y * scale

    ink, faint = "#465266", "#8b97a6"
    mono = "ui-monospace,SFMono-Regular,monospace"
    parts = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w:.0f} {h:.0f}" '
        f'width="100%" role="img" aria-label="generated PCB candidate, '
        f'{board.width:g} by {board.height:g} millimetres">',
        '<defs><marker id="bp-tick" viewBox="0 0 4 8" refX="2" refY="4" markerWidth="4" '
        'markerHeight="8" orient="auto"><path d="M2 0v8" stroke="' + faint +
        '" stroke-width="1"/></marker></defs>',
        f'<rect x="{px(0):.1f}" y="{py(0):.1f}" width="{board.width * scale:.1f}" '
        f'height="{board.height * scale:.1f}" rx="2" fill="#0f7a4d" fill-opacity="0.05" '
        f'stroke="#0b6b55" stroke-width="1.2"/>',
    ]
    for seg in board.segments:
        colour = "#c0282c" if seg.layer == "B.Cu" else "#1f5aa8"
        dash = ' stroke-dasharray="3 2"' if seg.layer == "B.Cu" else ""
        parts.append(f'<line x1="{px(seg.x1):.1f}" y1="{py(seg.y1):.1f}" x2="{px(seg.x2):.1f}" '
                     f'y2="{py(seg.y2):.1f}" stroke="{colour}" '
                     f'stroke-width="{max(1.2, seg.width * scale):.1f}" '
                     f'stroke-linecap="round"{dash}/>')
    for via in board.vias:
        parts.append(f'<circle cx="{px(via.x):.1f}" cy="{py(via.y):.1f}" '
                     f'r="{via.size * scale / 2:.1f}" fill="#ffffff" stroke="#1f5aa8" '
                     f'stroke-width="1.2"/>')
    for fp in board.footprints:
        parts.append(f'<rect x="{px(fp.x - fp.body_w / 2):.1f}" y="{py(fp.y - fp.body_h / 2):.1f}" '
                     f'width="{fp.body_w * scale:.1f}" height="{fp.body_h * scale:.1f}" '
                     f'fill="none" stroke="{faint}" stroke-width="0.8"/>')
        for inst in fp.pads:
            parts.append(f'<rect x="{px(inst.x - inst.w / 2):.1f}" '
                         f'y="{py(inst.y - inst.h / 2):.1f}" '
                         f'width="{inst.w * scale:.1f}" height="{inst.h * scale:.1f}" rx="0.4" '
                         f'fill="#a97f57" stroke="#7d5a38" stroke-width="0.6"/>')
        parts.append(f'<text x="{px(fp.x):.1f}" y="{py(fp.y - fp.height / 2 - 1.4):.1f}" '
                     f'font-family="{mono}" font-size="11" fill="{ink}" '
                     f'text-anchor="middle">{fp.ref}</text>')
    # horizontal dimension, above the board
    y_dim = top - 9.0
    parts.append(f'<line x1="{px(0):.1f}" y1="{y_dim:.1f}" x2="{px(board.width):.1f}" '
                 f'y2="{y_dim:.1f}" stroke="{faint}" stroke-width="0.8" '
                 f'marker-start="url(#bp-tick)" marker-end="url(#bp-tick)"/>')
    parts.append(f'<text x="{px(board.width / 2):.1f}" y="{y_dim - 3.5:.1f}" font-family="{mono}" '
                 f'font-size="9.5" fill="{ink}" text-anchor="middle">{board.width:g} mm</text>')
    # vertical dimension, left of the board
    x_dim = left - 12.0
    parts.append(f'<line x1="{x_dim:.1f}" y1="{py(0):.1f}" x2="{x_dim:.1f}" '
                 f'y2="{py(board.height):.1f}" stroke="{faint}" stroke-width="0.8" '
                 f'marker-start="url(#bp-tick)" marker-end="url(#bp-tick)"/>')
    parts.append(f'<text x="{x_dim - 6:.1f}" y="{py(board.height / 2):.1f}" font-family="{mono}" '
                 f'font-size="9.5" fill="{ink}" text-anchor="middle" '
                 f'transform="rotate(-90 {x_dim - 6:.1f} {py(board.height / 2):.1f})">'
                 f'{board.height:g} mm</text>')
    parts.append("</svg>")
    return "".join(parts)


def census(board: Board) -> dict:
    return {
        "width_mm": board.width,
        "height_mm": board.height,
        "footprints": len(board.footprints),
        "pads": len(board.pads()),
        "nets": len(board.nets()),
        "segments": len(board.segments),
        "vias": len(board.vias),
        "unrouted": len(board.unrouted),
        "layer_usage": {
            "F.Cu": len([s for s in board.segments if s.layer == "F.Cu"]),
            "B.Cu": len([s for s in board.segments if s.layer == "B.Cu"]),
        },
    }


def distance_point_segment(px: float, py: float, x1: float, y1: float,
                           x2: float, y2: float) -> float:
    dx, dy = x2 - x1, y2 - y1
    if dx == 0 and dy == 0:
        return math.hypot(px - x1, py - y1)
    t = max(0.0, min(1.0, ((px - x1) * dx + (py - y1) * dy) / (dx * dx + dy * dy)))
    return math.hypot(px - (x1 + t * dx), py - (y1 + t * dy))
